"""The dependency license policy behaves the way the report promises."""

from lct_tools.license_report import Dependency, render_report


def _dep(license_text: str) -> Dependency:
    return Dependency(ecosystem="npm", name="example", version="1.0.0", license=license_text)


def test_permissive_licenses_are_allowed() -> None:
    assert _dep("MIT").allowed
    assert _dep("Apache-2.0").allowed
    assert _dep("MPL-2.0").allowed


def test_a_choice_is_allowed_when_one_alternative_is() -> None:
    assert _dep("AFL-2.1 OR BSD-3-Clause").allowed


def test_a_combination_needs_every_term_allowed() -> None:
    assert not _dep("Apache-2.0 AND LGPL-3.0-or-later").allowed


def test_copyleft_and_unknown_licenses_are_rejected() -> None:
    assert not _dep("GPL-3.0-only").allowed
    assert not _dep("AGPL-3.0").allowed
    assert not _dep("UNKNOWN").allowed


def test_report_marks_itself_as_generated_and_lists_dependencies() -> None:
    text = render_report([_dep("MIT"), _dep("GPL-3.0-only")])
    assert text.startswith("<!-- Generated by")
    assert "Требуют проверки" in text
    assert "GPL-3.0-only" in text
