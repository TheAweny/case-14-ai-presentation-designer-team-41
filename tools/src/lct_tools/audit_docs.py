"""Generates `docs/AUDIT.md` from the check registries.

Checks over SlideIR are declared in `packages/slide-audit/src/checks.json`, contextual ones in
`packages/pipeline/src/audit/contextual-checks.json`; the TypeScript side imports both directly.
Checks of the engine are declared in `engine.checks.registry`. Keeping the document generated is
what stops it from drifting away from the code.
"""

import json
from dataclasses import dataclass
from pathlib import Path

from engine.checks import DETERMINISTIC_CHECKS

from lct_tools.paths import CONTEXTUAL_CHECKS_FILE, DOCS_DIR, SLIDE_CHECKS_FILE

__all__ = ["main", "render_audit_doc"]

_HEADER = """<!-- Generated by `yarn docs:audit`. Do not edit by hand:
     change the check registries and re-run the task. -->

# Аудит

Проверки делятся по тому, нужно ли для вывода понимать смысл слайда.

- **Детерминированные** — измеримые: геометрия, контраст, шрифты, остатки заглушек.
  - Проверки над SlideIR живут в TypeScript, в `packages/slide-audit`. Их запускает редактор после
    каждой правки и пайплайн после вёрстки.
  - Проверки движка живут в Python, в `engine.checks`. Там остаётся то, чему нужен сам файл
    `.pptx` или его рендер (решение от 2026-09-26 в `docs/DECISIONS.md`).
- **Контекстные** — смысловые: соответствует ли заголовок содержанию, подтверждён ли тезис
  контент-паком. Живут в TypeScript, в `packages/pipeline`.

Пороги задаются профилем в `configs/audit.yaml`.
"""


@dataclass(frozen=True, slots=True)
class _Row:
    id: str
    title: str
    description: str
    severity: str


def _json_rows(path: Path) -> list[_Row]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    return [
        _Row(
            id=item["id"],
            title=item["title"],
            description=item["description"],
            severity=item["severity"],
        )
        for item in raw["checks"]
    ]


def _table(rows: list[_Row]) -> str:
    lines = ["| id | Проверка | Уровень | Что проверяет |", "| --- | --- | --- | --- |"]
    for row in rows:
        lines.append(f"| `{row.id}` | {row.title} | {row.severity} | {row.description} |")
    return "\n".join(lines)


def render_audit_doc() -> str:
    """Build the full text of `docs/AUDIT.md`."""
    deterministic = [
        _Row(id=check.id, title=check.title, description=check.description, severity=check.severity)
        for check in DETERMINISTIC_CHECKS
    ]
    sections = [
        _HEADER,
        "## Детерминированные проверки над SlideIR (TypeScript, `packages/slide-audit`)",
        "",
        _table(_json_rows(SLIDE_CHECKS_FILE)),
        "",
        "## Проверки движка (Python, `engine.checks`)",
        "",
        _table(deterministic),
        "",
        "## Контекстные проверки (TypeScript, `packages/pipeline`)",
        "",
        _table(_json_rows(CONTEXTUAL_CHECKS_FILE)),
        "",
    ]
    return "\n".join(sections)


def main() -> int:
    """Write `docs/AUDIT.md` and report where it went."""
    target = DOCS_DIR / "AUDIT.md"
    target.write_text(render_audit_doc(), encoding="utf-8")
    print(f"wrote {target}")
    return 0
