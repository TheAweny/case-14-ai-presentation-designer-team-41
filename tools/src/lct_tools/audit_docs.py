"""Generates `docs/AUDIT.md` from the two check registries.

Deterministic checks are declared in `engine.checks.registry`; contextual ones in
`packages/pipeline/src/audit/contextual-checks.json`, which the TypeScript side imports directly.
Keeping the document generated is what stops it from drifting away from the code.
"""

import json
from dataclasses import dataclass

from engine.checks import DETERMINISTIC_CHECKS

from lct_tools.paths import CONTEXTUAL_CHECKS_FILE, DOCS_DIR

__all__ = ["main", "render_audit_doc"]

_HEADER = """<!-- Generated by `yarn docs:audit`. Do not edit by hand:
     change the check registries and re-run the task. -->

# Аудит

Проверки делятся по тому, нужно ли для вывода понимать смысл слайда.

- **Детерминированные** — измеримые: геометрия, контраст, количества, шрифты, остатки заглушек.
  Живут в Python-движке, в `engine.checks`.
- **Контекстные** — смысловые: соответствует ли заголовок содержанию, подтверждён ли тезис
  контент-паком. Живут в TypeScript, в `packages/pipeline`.

Пороги задаются профилем в `configs/audit.yaml`.
"""


@dataclass(frozen=True, slots=True)
class _Row:
    id: str
    title: str
    description: str
    severity: str


def _contextual_rows() -> list[_Row]:
    raw = json.loads(CONTEXTUAL_CHECKS_FILE.read_text(encoding="utf-8"))
    return [
        _Row(
            id=item["id"],
            title=item["title"],
            description=item["description"],
            severity=item["severity"],
        )
        for item in raw["checks"]
    ]


def _table(rows: list[_Row]) -> str:
    lines = ["| id | Проверка | Уровень | Что проверяет |", "| --- | --- | --- | --- |"]
    for row in rows:
        lines.append(f"| `{row.id}` | {row.title} | {row.severity} | {row.description} |")
    return "\n".join(lines)


def render_audit_doc() -> str:
    """Build the full text of `docs/AUDIT.md`."""
    deterministic = [
        _Row(id=check.id, title=check.title, description=check.description, severity=check.severity)
        for check in DETERMINISTIC_CHECKS
    ]
    sections = [
        _HEADER,
        "## Детерминированные проверки (Python, `engine.checks`)",
        "",
        _table(deterministic),
        "",
        "## Контекстные проверки (TypeScript, `packages/pipeline`)",
        "",
        _table(_contextual_rows()),
        "",
    ]
    return "\n".join(sections)


def main() -> int:
    """Write `docs/AUDIT.md` and report where it went."""
    target = DOCS_DIR / "AUDIT.md"
    target.write_text(render_audit_doc(), encoding="utf-8")
    print(f"wrote {target}")
    return 0
