import { BadRequestException } from '@nestjs/common';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { SlideIr } from '@lct/contracts';

const SINGLE_LIMIT = 1024 * 1024;
const TOTAL_LIMIT = 3 * SINGLE_LIMIT;
const PART = /^upload\/[\w.-]+\.(png|jpe?g)$/;
export interface ValidatedExportMedia {
  mediaPart: string;
  bytes: Buffer;
  extension: 'png' | 'jpg';
}

function dimensions(bytes: Buffer, type: string): { width: number; height: number } | null {
  if (type === 'png') {
    if (
      bytes.length < 33 ||
      !bytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])) ||
      bytes.readUInt32BE(8) !== 13 ||
      bytes.toString('ascii', 12, 16) !== 'IHDR'
    )
      return null;
    return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
  }
  if (
    bytes.length < 4 ||
    bytes[0] !== 255 ||
    bytes[1] !== 216 ||
    bytes.at(-2) !== 255 ||
    bytes.at(-1) !== 217
  )
    return null;
  let offset = 2;
  while (offset + 3 < bytes.length) {
    if (bytes[offset++] !== 255) return null;
    while (bytes[offset] === 255) offset++;
    const marker = bytes[offset++];
    if (marker === undefined || marker === 218 || marker === 217) return null;
    if (marker === 1 || (marker >= 208 && marker <= 215)) continue;
    if (offset + 2 > bytes.length) return null;
    const length = bytes.readUInt16BE(offset);
    if (length < 2 || offset + length > bytes.length) return null;
    if ([192, 193, 194, 195, 197, 198, 199, 201, 202, 203, 205, 206, 207].includes(marker)) {
      if (length < 8) return null;
      return { width: bytes.readUInt16BE(offset + 5), height: bytes.readUInt16BE(offset + 3) };
    }
    offset += length;
  }
  return null;
}

/** Validate every byte and reference before creating any files. No client paths are read. */
export function validateExportMedia(
  slides: readonly SlideIr[],
  input: unknown,
): ValidatedExportMedia[] {
  const fail = (): never => {
    throw new BadRequestException(
      'Invalid export media. Use referenced PNG/JPEG files, at most 32 files, 1 MiB each and 3 MiB total.',
    );
  };
  const referenced = new Set(
    slides.flatMap((slide) =>
      slide.elements.flatMap((element) =>
        element.kind === 'image' && element.mediaPart.startsWith('upload/')
          ? [element.mediaPart]
          : [],
      ),
    ),
  );
  if (referenced.size > 32 || [...referenced].some((part) => !PART.test(part))) fail();
  const entries = input === undefined ? [] : input;
  if (!Array.isArray(entries) || entries.length > 32) return fail();
  const seen = new Set<string>();
  const validated: ValidatedExportMedia[] = [];
  let total = 0;
  for (const entry of entries) {
    if (
      !entry ||
      typeof entry !== 'object' ||
      Array.isArray(entry) ||
      Object.keys(entry).some((key) => key !== 'mediaPart' && key !== 'dataUrl')
    )
      fail();
    const { mediaPart, dataUrl } = entry as { mediaPart?: unknown; dataUrl?: unknown };
    if (
      typeof mediaPart !== 'string' ||
      !PART.test(mediaPart) ||
      !referenced.has(mediaPart) ||
      seen.has(mediaPart) ||
      typeof dataUrl !== 'string' ||
      dataUrl.length > Math.ceil(SINGLE_LIMIT / 3) * 4 + 32
    )
      return fail();
    const match = /^data:image\/(png|jpeg);base64,([A-Za-z0-9+/]+={0,2})$/.exec(dataUrl);
    if (
      !match?.[1] ||
      !match[2] ||
      match[2].length % 4 !== 0 ||
      (match[1] === 'png') !== /\.png$/i.test(mediaPart)
    )
      return fail();
    const bytes = Buffer.from(match[2], 'base64');
    total += bytes.length;
    if (
      !bytes.length ||
      bytes.length > SINGLE_LIMIT ||
      total > TOTAL_LIMIT ||
      bytes.toString('base64') !== match[2]
    )
      fail();
    const size = dimensions(bytes, match[1]);
    if (
      !size ||
      size.width < 1 ||
      size.height < 1 ||
      size.width > 8192 ||
      size.height > 8192 ||
      size.width * size.height > 40_000_000
    )
      fail();
    seen.add(mediaPart);
    validated.push({ mediaPart, bytes, extension: match[1] === 'png' ? 'png' : 'jpg' });
  }
  if (seen.size !== referenced.size) fail();
  return validated;
}

/** outputDir is generated by the server after checking completed-deck ownership. */
export async function writeExportMedia(
  outputDir: string,
  media: readonly ValidatedExportMedia[],
): Promise<{ mediaPart: string; path: string }[]> {
  if (!media.length) return [];
  const directory = join(outputDir, 'media');
  await mkdir(directory, { recursive: true });
  const result: { mediaPart: string; path: string }[] = [];
  const written = new Set<string>();
  for (const entry of media) {
    const hash = createHash('sha256').update(entry.bytes).digest('hex');
    const path = join(directory, `${hash}.${entry.extension}`);
    if (!written.has(path)) {
      await writeFile(path, entry.bytes, { flag: 'wx' });
      written.add(path);
    }
    result.push({ mediaPart: entry.mediaPart, path });
  }
  return result;
}
